def _awning_on_gable(bm, kind, ox, oy, rot, half_len, side_sign=1.0, **kw):
    """Back a yard shelter onto a building's gable end (local +/-X), like an
    attached lean-to tucked against the wall."""
    nx, ny = math.cos(rot) * side_sign, math.sin(rot) * side_sign
    depth = kw.get('depth', 2.4)
    off = half_len + depth * 0.5 + 0.05
    _build_awning_at(bm, kind, cx=ox + nx * off, cy=oy + ny * off, z_base=0.0,
                     rot_z=rot + side_sign * math.pi * 0.5, **kw)


def _place_estate_awnings(bm, props, tier, spread_x, fore_y, stable=None, servant=None):
    """Rustic yard shelters stocked as private little stores.

    Each is backed against an outbuilding's gable end when that outbuilding exists
    (so they read as attached lean-tos, not floating in the courtyard); otherwise
    they fall back to the open forecourt.
    """
    shelters = (
        ('TARP', stable, -spread_x * 0.55, 'LEANTO', 3.4, 2.8, 2.25, 2.80),
        ('LEANTO', servant, spread_x * 0.55, 'TARP', 2.8, 2.4, 1.95, 2.55),
    )
    for kind, slot, fallback_x, _other, width, depth, fh, bh in shelters:
        if slot is not None:
            ox, oy, rot, olen = slot
            outward = 1.0 if (math.cos(rot) * ox + math.sin(rot) * oy) >= 0.0 else -1.0
            nx, ny = math.cos(rot) * outward, math.sin(rot) * outward
            off = olen * 0.5 + depth * 0.5 + 0.05
            cx, cy = ox + nx * off, oy + ny * off
            aw_rot = rot + outward * math.pi * 0.5
        else:
            cx, cy = fallback_x, fore_y + 4.8
            aw_rot = 0.0 if kind == 'TARP' else math.pi * 0.5
        _build_awning_at(bm, kind, cx=cx, cy=cy, z_base=0.0, rot_z=aw_rot,
                         width=width, depth=depth, front_h=fh, back_h=bh)
        _stock_shelter(bm, cx, cy, 1.0 if cx >= 0.0 else -1.0)


def build_estate_outbuildings(bm, props, ctx):
    """
    High-level orchestrator called during architectural accessories dispatch.
    Places the detached stables, servant quarters, courtyard fountain and awnings
    procedurally according to scene properties.
    """
    tier = getattr(props, 'material_tier', 'TIER_1')
    has_stable = getattr(props, 'has_stable', False)
    has_servants = getattr(props, 'has_servant_quarters', False)
    has_fountain = getattr(props, 'has_estate_fountain', False)
    has_awnings = getattr(props, 'estate_awnings', False)

    if not (has_stable or has_servants or has_fountain or has_awnings):
        return

    spread_x = getattr(props, 'outbuilding_offset_x', 24.0)
    fore_y = getattr(props, 'outbuilding_offset_y', -10.0)
    stable_side = getattr(props, 'stable_side', 'LEFT')
    servant_side = getattr(props, 'servant_quarters_side', 'RIGHT')
    setback = getattr(props, 'plot_setback', 0.0)
    base_hy = ctx.base_d * 0.5

    # 1. Central Courtyard Fountain — centred in the (now deeper) honor court.
    if has_fountain:
        manor_front = setback - base_hy
        fountain_y = (fore_y + manor_front) * 0.5
        fountain_y = min(fountain_y, fore_y + 2.0)
        build_estate_fountain(bm, pos=(0.0, fountain_y, 0.0), tier=tier)

    stable_slot = None
    servant_slot = None

    # 2. Horse Stable & Carriage Barn
    if has_stable:
        st_sgn = -1.0 if stable_side == 'LEFT' else 1.0
        st_x = st_sgn * spread_x
        st_y = fore_y
        # Rotate 90 deg so the carriage door faces the courtyard, not the field.
        # Auto on very wide plots, or whenever the preset explicitly asks for it.
        _rot_on = getattr(props, 'stable_rotate', False) or spread_x > 18.0
        st_rot = -math.pi * 0.5 * st_sgn if _rot_on else 0.0
        build_stable(bm, props, pos=(st_x, st_y, 0.0), rot_z=st_rot, tier=tier)
        stable_slot = (st_x, st_y, st_rot, _stable_dims(tier)[0])

    # 3. Servant Quarters / Steward Lodge
    if has_servants:
        sq_sgn = -1.0 if servant_side == 'LEFT' else 1.0
        sq_x = sq_sgn * spread_x
        sq_y = fore_y
        sq_rot = -math.pi * 0.5 * sq_sgn if spread_x > 18.0 else 0.0
        sq_w = 13.5 if tier == 'TIER_3' else (12.0 if tier == 'TIER_2' else 10.5)
        sq_d = 7.5 if tier == 'TIER_3' else 6.8
        sq_fl = 2 if tier in ('TIER_2', 'TIER_3') else 1
        build_servant_quarters(
            bm, props, pos=(sq_x, sq_y, 0.0), rot_z=sq_rot, tier=tier,
            width=sq_w, depth=sq_d, floors=sq_fl
        )
        servant_slot = (sq_x, sq_y, sq_rot, sq_w)

    # 4. Yard shelters backed onto the outbuilding gables
    if has_awnings:
        _place_estate_awnings(bm, props, tier, spread_x, fore_y,
                              stable=stable_slot, servant=servant_slot)
