# Estate/fotification toggles that must never be inherited by a generated outbuilding,
# otherwise every stable would recursively spawn its own stables and walls.
_OUTHOUSE_DISABLED = (
    'has_stable', 'has_servant_quarters', 'has_estate_fountain',
    'has_palisade', 'has_curtain_wall', 'has_banners',
    'has_bastion_towers', 'has_military_props', 'has_mounted_shields',
    'has_gable_crest', 'has_side_annex', 'has_mini_wing',
    'has_balcony', 'has_corner_turrets', 'has_clock_tower',
    'has_veranda', 'has_trade_sign', 'has_flower_boxes',
    'has_outdoor_decor', 'has_well', 'has_arched_porch',
    'has_side_rampart', 'has_pillared_overhang',
)

_INHERITED = (
    'color_shingles', 'color_wall_ext', 'color_timber', 'color_stone',
    'color_floor', 'color_timber_frame', 'window_glow_strength',
    'include_door_leaves',
)


def _merge_generated_building(bm, base_props, overrides, pos=0.0, rot_z=0.0, preset_key=None):
    """Generate a detached building with the real pipeline and merge it into ``bm``.

    Builds a genuine miniature building using :func:`generate_building` (same walls,
    floors, openings, roof and materials as the main manor), bakes the placement
    transform into a temporary mesh, then appends it to the shared bmesh. Material
    slot indices line up because both meshes use the same canonical slot order.

    When ``preset_key`` names a real style preset the outhouse is generated from that
    preset (e.g. the dedicated STABLE barn presets), with ``overrides`` then tuning the
    footprint and the placement.
    """
    import bpy
    from ..building import generate_building

    scene = bpy.data.scenes.new("_bbc_outhouse")
    mesh = bpy.data.meshes.new("_bbc_outhouse_mesh")
    obj = bpy.data.objects.new("_bbc_outhouse", mesh)
    try:
        op = scene.fantasy_building_settings
        op.auto_update = False
        op.building_archetype = 'NONE'
        if preset_key:
            try:
                from ...presets import PRESETS, apply_preset
                if preset_key in PRESETS:
                    apply_preset(op, preset_key)
                    op.auto_update = False
                    op.building_archetype = 'NONE'
            except Exception:
                pass
        op.material_tier = getattr(base_props, 'material_tier', 'TIER_1')
        for _ck in _INHERITED:
            if hasattr(base_props, _ck) and hasattr(op, _ck):
                try:
                    setattr(op, _ck, getattr(base_props, _ck))
                except Exception:
                    pass
        for _fk in _OUTHOUSE_DISABLED:
            if hasattr(op, _fk):
                try:
                    setattr(op, _fk, False)
                except Exception:
                    pass
        for k, v in overrides.items():
            if hasattr(op, k):
                try:
                    setattr(op, k, v)
                except Exception:
                    pass

        generate_building(obj, op)

        mat = (Matrix.Translation(Vector(pos)) @ Matrix.Rotation(rot_z, 4, 'Z'))
        mesh.transform(mat)
        bm.from_mesh(mesh)
    finally:
        bpy.data.objects.remove(obj, do_unlink=True)
        bpy.data.meshes.remove(mesh)
        bpy.data.scenes.remove(scene)


def _stable_key(tier):
    """Map a material tier ('TIER_1') to its STABLE preset key ('STABLE_T1')."""
    suffix = tier[-1] if tier else '1'
    return 'STABLE_T%s' % suffix


def _stable_dims(tier):
    """Footprint of the STABLE_<tier> preset, shared by the barn and the yard."""
    try:
        from ...presets import PRESETS
        s = PRESETS.get(_stable_key(tier), {}).get('settings', {})
        return s.get('width', 12.0), s.get('depth', 8.0)
    except Exception:
        return 12.0, 8.0


def build_stable(bm, props, pos=(-24.0, -10.0, 0.0), rot_z=0.0, tier='TIER_1'):
    """Detached horse stable & carriage barn.

    The ``STABLE_<tier>`` preset is the single source of truth for the barn (walls,
    timber door, roof — no foundation, no steps, no dormers), so a standalone stable
    built from that preset matches this estate outbuilding exactly. The working yard
    (stall row + paddock pen) is added by the same shared yard builder.
    """
    _merge_generated_building(bm, props, {}, pos=pos, rot_z=rot_z,
                              preset_key=_stable_key(tier))
    bw, bd = _stable_dims(tier)
    t = Matrix.Translation(Vector(pos)) @ Matrix.Rotation(rot_z, 4, 'Z')
    _build_stable_yard(bm, t, bw, bd, tier)


def build_stable_yard_for_building(bm, props, ctx):
    """Build the stall row + paddock pen when the main building itself is a stable.

    Called from the archetype dispatch so a standalone STABLE preset gets the same
    yard as the estate stable, keeping the two paths identical.
    """
    tier = getattr(props, 'material_tier', 'TIER_1')
    bw, bd = _stable_dims(tier)
    _build_stable_yard(bm, Matrix.Identity(4), bw, bd, tier)


def _local_box(bm, t, size, loc, mat=MAT_INDEX_TIMBER, bevel=0.01, rot=(0.0, 0.0, 0.0)):
    """Place a beveled box in an outbuilding's rotated local frame."""
    return create_beveled_box(
        bm, size=size, location=loc, rotation=rot,
        transform_matrix=t, mat_index=mat, bevel_amount=bevel,
    )


def _build_stall_shelter(bm, t, x0, x1, y_back, depth, tier='TIER_1', stalls=3,
                         back_h=2.15, front_h=2.15):
    """Open-front timber stall row with a framed lean-to roof, opening toward -Y.

    Tier 1 gets a simple cloth/plank skin over a visible rafter frame (lumbermill
    feel); higher tiers get shingles. The shelter is a flat-roofed run-in shed, so
    the back wall, stall dividers and both end walls all share one height (nothing
    steps or pokes through); only the open front is framed by posts.
    """
    w = x1 - x0
    cx = (x0 + x1) * 0.5
    y_front = y_back - depth
    slope = back_h - front_h
    ang = math.atan2(slope, depth)
    rl = math.hypot(depth, slope)
    mid_y = y_back - depth * 0.5
    roof_mid_z = (back_h + front_h) * 0.5
    # One shared wall height for the back wall, dividers and ends: it clears the
    # roof underside everywhere the roof is lowest.
    wall_h = min(back_h, front_h) - 0.05

    # Plank back wall.
    plank_h = 0.24
    for i in range(int(wall_h / plank_h)):
        _local_box(bm, t, (w, 0.10, min(plank_h * 0.94, wall_h - i * plank_h)),
                   (cx, y_back, plank_h * (i + 0.5)), mat=MAT_INDEX_WOOD, bevel=0.008)
    # Front posts.
    for i in range(stalls + 1):
        px = x0 + w * i / stalls
        _local_box(bm, t, (0.16, 0.16, front_h), (px, y_front, front_h * 0.5),
                   mat=MAT_INDEX_TIMBER, bevel=0.012)
    # Solid divider walls between stalls, at the same height as the back wall.
    for i in range(1, stalls):
        px = x0 + w * i / stalls
        _local_box(bm, t, (0.10, depth, wall_h),
                   (px, y_back - depth * 0.5, wall_h * 0.5), mat=MAT_INDEX_WOOD, bevel=0.008)
    # Solid end walls close both flanks, matching the back wall height.
    for sx in (x0, x1):
        _local_box(bm, t, (0.10, depth, wall_h), (sx, y_back - depth * 0.5, wall_h * 0.5),
                   mat=MAT_INDEX_WOOD, bevel=0.008)

    # Rafter frame: front header on the posts and a back plate sitting on the wall.
    _local_box(bm, t, (w + 0.20, 0.14, 0.16), (cx, y_front, front_h + 0.02),
               mat=MAT_INDEX_TIMBER, bevel=0.008)
    _local_box(bm, t, (w + 0.20, 0.14, 0.16), (cx, y_back, wall_h + 0.08),
               mat=MAT_INDEX_TIMBER, bevel=0.008)
    for i in range(stalls + 1):
        rx = x0 + w * i / stalls
        _local_box(bm, t, (0.09, rl + 0.10, 0.09), (rx, mid_y, roof_mid_z + 0.10),
                   rot=(ang, 0.0, 0.0), mat=MAT_INDEX_TIMBER, bevel=0.006)

    # Roof slab, framed by bargeboards (sides) and a fascia board (front eave).
    roof_mat = MAT_INDEX_TARP if tier == 'TIER_1' else MAT_INDEX_SHINGLES
    roof_faces = _local_box(
        bm, t, (w + 0.34, rl + 0.30, 0.055),
        (cx, mid_y, roof_mid_z + 0.17), rot=(ang, 0.0, 0.0),
        mat=roof_mat, bevel=0.006)
    half_rl = rl * 0.5 + 0.15
    front_y = mid_y - half_rl * math.cos(ang)
    front_z = roof_mid_z + 0.17 - half_rl * math.sin(ang)
    _local_box(bm, t, (w + 0.40, 0.11, 0.16), (cx, front_y, front_z),
               rot=(ang, 0.0, 0.0), mat=MAT_INDEX_TIMBER, bevel=0.008)
    for s in (-1.0, 1.0):
        _local_box(bm, t, (0.12, rl + 0.30, 0.16),
                   (cx + s * (w * 0.5 + 0.17), mid_y, roof_mid_z + 0.16),
                   rot=(ang, 0.0, 0.0), mat=MAT_INDEX_TIMBER, bevel=0.008)

    # Match the main-roof shingle UVs (correct axis + 0.32 tiles/m) instead of the
    # default box mapping that leaves the tiles rotated and mis-scaled.
    if roof_mat == MAT_INDEX_SHINGLES:
        from ..roof.shingles import map_lean_to_shingle_uvs
        loc_world = t @ Vector((cx, mid_y, roof_mid_z + 0.17))
        rot_world = (t.to_3x3() @ Euler((ang, 0.0, 0.0), 'XYZ').to_matrix()).to_euler()
        map_lean_to_shingle_uvs(bm, roof_faces, loc_world, rot_world,
                                u_scale=0.32, v_scale=0.32)


def _build_pen_fence(bm, t, x0, x1, y0, y1, gate_w=1.7, post_h=1.25):
    """A rail-and-post paddock fence around the pen, with a gate gap on the -Y side."""
    def run(ax, ay, bx, by):
        length = math.hypot(bx - ax, by - ay)
        n = max(1, int(round(length / 1.6)))
        ang = math.atan2(by - ay, bx - ax)
        for i in range(n + 1):
            fx = ax + (bx - ax) * i / n
            fy = ay + (by - ay) * i / n
            _local_box(bm, t, (0.14, 0.14, post_h), (fx, fy, post_h * 0.5),
                       mat=MAT_INDEX_TIMBER, bevel=0.010)
        for rz in (0.50, 1.00):
            _local_box(bm, t, (length + 0.08, 0.08, 0.10),
                       ((ax + bx) * 0.5, (ay + by) * 0.5, rz),
                       rot=(0.0, 0.0, ang), mat=MAT_INDEX_TIMBER, bevel=0.006)

    run(x0, y0, x0, y1)                 # left flank
    run(x1, y0, x1, y1)                 # right flank
    # NOTE: no rail across the barn facade — it would block the carriage door.
    # Courtyard side split by a gate opening aligned with the barn door.
    gate_lo = -gate_w * 0.5
    gate_hi = gate_w * 0.5
    run(x0, y1, gate_lo, y1)
    run(gate_hi, y1, x1, y1)
    for gx in (gate_lo, gate_hi):
        _local_box(bm, t, (0.18, 0.18, post_h + 0.35), (gx, y1, (post_h + 0.35) * 0.5),
                   mat=MAT_INDEX_TIMBER, bevel=0.014)


def _build_stable_yard(bm, t, barn_w, barn_d, tier):
    """Compose the stable yard: fenced paddock plus a roofed open stall row.

    The pen is open along the barn facade (no rail in front of the carriage door)
    so horses and carts can be walked straight in through the gate.
    """
    barn_front = -barn_d * 0.5
    pen_d = 6.0
    pen_w = barn_w + 1.0
    x0, x1 = -pen_w * 0.5, pen_w * 0.5
    y0 = barn_front - 0.30            # barn side of the pen
    y1 = barn_front - pen_d           # courtyard side

    # Open stall row tucked along the left side of the pen, opening to the court.
    stall_w = min(pen_w * 0.5, 4.2)
    _build_stall_shelter(bm, t, x0 + 0.15, x0 + 0.15 + stall_w, y0 - 0.20, 3.0,
                         tier=tier, stalls=3)
    _build_pen_fence(bm, t, x0, x1, y0, y1)


